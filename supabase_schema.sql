-- 1. USERS TABLE (Admin, Faculty, and Student Authentication)
CREATE TABLE IF NOT EXISTS public.users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username TEXT UNIQUE NOT NULL,
    password_hash TEXT NOT NULL,
    role TEXT NOT NULL CHECK(role IN ('admin', 'faculty', 'student')),
    name TEXT NOT NULL,
    email TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. STUDENTS TABLE (Demographics & Academic Registration)
CREATE TABLE IF NOT EXISTS public.students (
    register_number TEXT PRIMARY KEY,
    name TEXT NOT NULL,
    dob TEXT NOT NULL, -- DD/MM/YYYY
    department TEXT NOT NULL,
    degree TEXT NOT NULL,
    regulation TEXT DEFAULT 'CBCS Regulation 2023',
    current_semester TEXT DEFAULT 'Semester IV',
    admission_year INTEGER DEFAULT 2023,
    mentor TEXT,
    gender TEXT DEFAULT 'Not Specified',
    blood_group TEXT DEFAULT '--',
    email TEXT,
    phone TEXT,
    guardian_name TEXT,
    address TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. SUBJECTS TABLE (Autonomous CBCS Curriculum Catalog)
CREATE TABLE IF NOT EXISTS public.subjects (
    code TEXT PRIMARY KEY,
    name TEXT NOT NULL,
    credits INTEGER NOT NULL DEFAULT 4,
    semester TEXT NOT NULL,
    department TEXT NOT NULL,
    max_internal INTEGER NOT NULL DEFAULT 25,
    max_external INTEGER NOT NULL DEFAULT 75
);

-- 4. MARKS TABLE (Scores, Grades, GPA & Examination Sessions)
CREATE TABLE IF NOT EXISTS public.marks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    register_number TEXT NOT NULL REFERENCES public.students(register_number) ON DELETE CASCADE,
    subject_code TEXT NOT NULL REFERENCES public.subjects(code) ON DELETE CASCADE,
    semester TEXT NOT NULL,
    academic_year TEXT NOT NULL,
    exam_type TEXT NOT NULL,
    internal_mark NUMERIC(5,2) NOT NULL,
    external_mark NUMERIC(5,2) NOT NULL,
    total_mark NUMERIC(5,2) NOT NULL,
    grade_point INTEGER NOT NULL,
    letter_grade TEXT NOT NULL,
    result TEXT NOT NULL,
    updated_at TIMESTAMPTZ DEFAULT NOW(),
    updated_by TEXT DEFAULT 'system',
    UNIQUE(register_number, subject_code, semester, academic_year, exam_type)
);

-- Indexes for lightning-fast queries
CREATE INDEX IF NOT EXISTS idx_marks_student ON public.marks(register_number);
CREATE INDEX IF NOT EXISTS idx_marks_session ON public.marks(semester, academic_year, exam_type);
CREATE INDEX IF NOT EXISTS idx_students_search ON public.students(name, department);

-- 5. ROW LEVEL SECURITY (RLS) POLICIES
-- Enable RLS
ALTER TABLE public.users ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.students ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.subjects ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.marks ENABLE ROW LEVEL SECURITY;

-- Allow anon and service_role full CRUD access for web portal API
DO $$
BEGIN
    DROP POLICY IF EXISTS "Public access for users" ON public.users;
    DROP POLICY IF EXISTS "Public access for students" ON public.students;
    DROP POLICY IF EXISTS "Public access for subjects" ON public.subjects;
    DROP POLICY IF EXISTS "Public access for marks" ON public.marks;

    CREATE POLICY "Public access for users" ON public.users FOR ALL USING (true) WITH CHECK (true);
    CREATE POLICY "Public access for students" ON public.students FOR ALL USING (true) WITH CHECK (true);
    CREATE POLICY "Public access for subjects" ON public.subjects FOR ALL USING (true) WITH CHECK (true);
    CREATE POLICY "Public access for marks" ON public.marks FOR ALL USING (true) WITH CHECK (true);
END $$;

